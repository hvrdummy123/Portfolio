/** Compact row-major 16x16 frames. Rows are strings of hex nybbles 0-6. */
function decode(rows: string[]): number[] {
  const out: number[] = [];
  for (const row of rows) {
    for (const ch of row) out.push(parseInt(ch, 16));
  }
  return out;
}

